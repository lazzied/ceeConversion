"""Generate LaTeX document preambles from exam metadata and used features."""

from typing import Any

from latex_converter.models import RenderOptions


def escape_percent(text: str) -> str:
    """Escape literal percent signs in metadata without changing math spans."""
    import re
    chunks: list[str] = []
    position = 0
    for match in re.finditer(r"(?<!\\)\$.*?(?<!\\)\$", text, re.S):
        chunks.append(re.sub(r"(?<!\\)%", r"\\%", text[position:match.start()]))
        chunks.append(match.group())
        position = match.end()
    chunks.append(re.sub(r"(?<!\\)%", r"\\%", text[position:]))
    return "".join(chunks)


def build_preamble(data: dict[str, Any], uses: set[str], options: RenderOptions) -> str:
    """Build a black-and-white preamble containing only needed packages."""
    meta = data.get("metadata") or {}
    src = meta.get("source_file")
    preamble_lines: list[str] = []
    preamble_lines += ["% Generated by exam_latex"
          + (f" from {src}" if src else "")
          + f" (schema {data.get('schema_version', '?')}).",
          "% Compile with XeLaTeX or LuaLaTeX:  xelatex <this file>",
          rf"\documentclass[UTF8,{options.font_size}]{{{options.document_class}}}", ""]

    preamble_lines += ["% ---------- Packages ----------",
          r"\usepackage{amsmath,amssymb,bm}",
          r"\usepackage[a4paper,top=2.8cm,bottom=2.5cm,left=2.4cm,right=2.4cm]{geometry}",
          r"\usepackage{enumitem}      % questions / sub-questions / statements",
          r"\usepackage{fancyhdr}      % running header and footer"]
    if "tasks" in uses:
        preamble_lines.append(r"\usepackage{tasks}         % multiple-choice options")
    if "needspace" in uses:
        preamble_lines.append(r"\usepackage{needspace}     % keep tall questions on one page")
    if "booktabs" in uses:
        preamble_lines.append(r"\usepackage{booktabs}      % table rules")
    if "graphicx" in uses:
        preamble_lines.append(r"\usepackage{graphicx}      % real figures")
    preamble_lines.append("")

    if "circled" in uses:
        preamble_lines += ["% ---------- Fonts ----------",
              "% xeCJK does not treat circled digits (① ② ...) as CJK by default, so they",
              "% would come from the Latin font and be missing. Use the CJK font instead.",
              r'\ifdefined\xeCJKsetcharclass\xeCJKsetcharclass{"2460}{"24FF}{1}\fi', ""]

    if meta.get("title") or meta.get("header_left"):
        preamble_lines += ["% ---------- Exam metadata ----------"]
        for macro, key in (("examtitle", "title"), ("examsubtitle", "subtitle"),
                           ("examheaderleft", "header_left"),
                           ("examheaderright", "header_right")):
            if meta.get(key):
                preamble_lines.append(rf"\newcommand{{\{macro}}}{{{escape_percent(str(meta[key]))}}}")
        preamble_lines.append("")

    preamble_lines += ["% ---------- Page style ----------",
          r"\pagestyle{fancy}",
          r"\fancyhf{}",
          r"\setlength{\headheight}{24.1pt}",
          r"\renewcommand{\headrulewidth}{0pt}"]
    if meta.get("header_left"):
        preamble_lines.append(r"\fancyhead[L]{\small\examheaderleft}")
    if meta.get("header_right"):
        preamble_lines.append(r"\fancyhead[R]{\small\examheaderright}")
    preamble_lines += [r"\fancyfoot[C]{\small\thepage}",
          "",
          r"\setlength{\parindent}{0pt}",
          r"\setlength{\parskip}{0.5em}",
          r"\linespread{1.25}",
          r"\renewcommand{\arraystretch}{1.3}   % roomier tables", "",
          "% ---------- Section headings ----------",
          r"\ctexset{section={format=\large\bfseries, beforeskip=1.6em, afterskip=0.8em}}", ""]

    preamble_lines += ["% ---------- Lists ----------",
          r"\newlist{questions}{enumerate}{1}",
          r"\setlist[questions]{label=\textbf{\arabic*.},",
          r"  leftmargin=2.2em, itemsep=1.1em, topsep=0pt, parsep=0.4em}",
          "",
          r"\newlist{subquestions}{enumerate}{2}",
          r"\setlist[subquestions,1]{label=(\arabic*), leftmargin=2.6em,",
          r"  itemsep=0.3em, topsep=0.2em, parsep=0pt}",
          r"\setlist[subquestions,2]{label=(\alph*), leftmargin=2.4em,",
          r"  itemsep=0.2em, topsep=0.1em, parsep=0pt}",
          "",
          r"\newlist{statements}{description}{1}   % ① ② ③ ④ propositions",
          r"\setlist[statements]{font=\normalfont, align=left, leftmargin=3em,",
          r"  labelwidth=1.6em, labelsep=0.4em, itemsep=0.1em, topsep=0.2em, parsep=0pt}",
          ""]
    preamble_lines.append("")

    if "tasks" in uses:
        preamble_lines += ["% ---------- Multiple-choice options ----------",
              r"\settasks{label=(\Alph*), label-width=1.8em, column-sep=1em,",
              r"  before-skip=0.2em, after-skip=0.2em, after-item-skip=0.2em}", ""]

    macros: list[str] = []
    if "blank" in uses:
        macros += [r"\newcommand{\blank}{\underline{\hspace{4em}}}   % fill-in blank"]
    if "choiceparen" in uses:
        macros += [r"\newcommand{\choiceparen}{（\hspace{2em}）}      % answer bracket"]
    if "boxlabel" in uses:
        macros += [r"\newcommand{\boxlabel}[1]{{\bfseries #1}\quad}  % label of a reference note"]
    if "reference" in uses:
        macros += [r"\newenvironment{reference}%   unframed note, never split across pages",
                   r"  {\par\smallskip\noindent\begin{minipage}{\linewidth}}",
                   r"  {\end{minipage}\par\smallskip}"]
    if "placeholder" in uses:
        macros += [r"\newcommand{\examfigure}[3]{%   width (cm), height (cm), label",
                   r"  \parbox[c][#2cm][c]{#1cm}{\centering\small\textit{[ #3 ]}}}"]
    if meta.get("title"):
        macros += [r"\newcommand{\makeexamtitle}{%",
                   r"  \begin{center}",
                   r"    {\LARGE\bfseries\examtitle}\par"]
        if meta.get("subtitle"):
            macros += [r"    \vspace{0.4em}{\Large\bfseries\examsubtitle}\par"]
        macros += [r"  \end{center}\vspace{0.4em}}"]
    if macros:
        preamble_lines += ["% ---------- Macros ----------"] + macros + [""]
    return "\n".join(preamble_lines) + "\n"
